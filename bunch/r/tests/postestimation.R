library(specbunch)
z <- seq(-.5,.5,length.out=5000);x <- rep(.4,length(z))
f <- structure(list(B=.08,sigma=.03,a=0,friction="gaussian",kink=0,window_lo=12,window_hi=45,refused=FALSE),class="specbunch_mass")
r <- nonbuncher_mean(z,x,f,mu_b=.4)
stopifnot(!r$refused,abs(r$m_NB-.4)<1e-10,is.data.frame(r$local_fit),nrow(r$local_fit)==40,r$pi_kink>0)
r2 <- nonbuncher_mean(z,x,f,mu_b=.4,degree=2,threads=4)
stopifnot(abs(r2$m_NB-.4)<1e-10)
e <- eti(f,z,net_below=1.34,net_above=1)
stopifnot(!e$refused,abs(e$saez$e-e$saez$d/log(1.34))<1e-14)
stopifnot(inherits(try(eti(f,z,net_below=1,net_above=1),silent=TRUE),"try-error"))
